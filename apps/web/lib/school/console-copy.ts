export const consoleCopy = { en, bn };

export function useConsoleCopy() {
  const school = useSchoolLanguage();
  const { language } = school;
  const format = useMemo(
    () => new Intl.NumberFormat(language === 'bn' ? 'bn-BD' : 'en'),
    [language],
  );
  /** Numbers in the reader's numerals: Bengali digits in Bangla, Latin in English. */
  const n = useCallback((value: number) => format.format(value), [format]);
  const c = useCallback(
    (key: ConsoleString, vars: Record<string, string | number> = {}) =>
      (language === 'bn' ? bn : en)[key].replace(/\{(\w+)\}/g, (_, name: string) => {
        const value = vars[name];
        return typeof value === 'number' ? format.format(value) : (value ?? '');
      }),
    [language, format],
  );
  return { ...school, c, n };
}
